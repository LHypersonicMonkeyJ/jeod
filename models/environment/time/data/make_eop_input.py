#!/usr/bin/env python3
"""Build the EOP input file read by the TAI-UT1 and polar motion parsers.

The IERS 14 C04 series that JEOD originally used was discontinued in 2023
(last update January 2026). This script merges:

  * IERS 20 C04 (final values, daily at 0h UTC), and
  * IERS finals2000A.all (Bulletin A rapid values and ~1 year of predictions)
    for the days after the last 20 C04 entry,

and writes them in the 14 C04 column layout that parser.py (time/data) and
RNP/RNPJ2000/data/polar_motion/parser.py already read. Only date, MJD, x, y
and UT1-UTC are used by JEOD; the remaining columns are carried along where
available and written as zero otherwise.

Usage (from this directory):
  ./make_eop_input.py                        # download both inputs
  ./make_eop_input.py -c <eopc04.1962-now> -f <finals2000A.all>
then:
  python3 parser.py -i eop_c04_20_finals.62-now [-s]
  cd ../../RNP/RNPJ2000/data/polar_motion && python3 parser.py -i eop_c04_20_finals.62-now
and format the regenerated src/*.cc files with the repository .clang-format.
"""

import argparse
import datetime
import urllib.request

C04_URL = 'https://hpiers.obspm.fr/iers/eop/eopc04/eopc04.1962-now'
FINALS_URL = 'https://datacenter.iers.org/data/9/finals2000A.all'
OUTPUT = 'eop_c04_20_finals.62-now'
MJD_EPOCH = datetime.date(1858, 11, 17)


def read_lines(path, url):
    if path:
        with open(path) as f:
            return f.read().splitlines()
    print('Downloading {0}'.format(url))
    with urllib.request.urlopen(url, timeout=120) as resp:
        return resp.read().decode('ascii', 'replace').splitlines()


def parse_c04_20(lines):
    """IERS 20 C04: YR MM DD HH MJD x y UT1-UTC dX dY xrt yrt LOD + errors."""
    rows = []
    for line in lines:
        if line.startswith('#') or not line.strip():
            continue
        ss = line.split()
        rows.append(dict(
            mjd=int(round(float(ss[4]))),
            x=float(ss[5]), y=float(ss[6]), dut=float(ss[7]),
            lod=float(ss[12]), dx=float(ss[8]), dy=float(ss[9]),
            x_err=float(ss[13]), y_err=float(ss[14]), dut_err=float(ss[15]),
            lod_err=float(ss[20]), dx_err=float(ss[16]), dy_err=float(ss[17])))
    return rows


def field(line, start, end, scale=1.0):
    """Fixed-width finals2000A field (1-based inclusive columns), 0 if blank."""
    text = line[start - 1:end].strip()
    return float(text) * scale if text else 0.0


def parse_finals(lines):
    """IERS finals2000A.all (Bulletin A), rows with a UT1-UTC value."""
    rows = []
    for line in lines:
        if len(line) < 68 or line[57] not in 'IP':
            continue
        rows.append(dict(
            mjd=int(round(float(line[7:15]))),
            x=field(line, 19, 27), y=field(line, 38, 46), dut=field(line, 59, 68),
            lod=field(line, 80, 86, 1e-3),
            dx=field(line, 98, 106, 1e-3), dy=field(line, 117, 125, 1e-3),
            x_err=field(line, 28, 36), y_err=field(line, 47, 55),
            dut_err=field(line, 69, 78), lod_err=field(line, 87, 93, 1e-3),
            dx_err=field(line, 107, 115, 1e-3), dy_err=field(line, 126, 134, 1e-3),
            predicted=line[57] == 'P'))
    return rows


def format_row(r):
    d = MJD_EPOCH + datetime.timedelta(days=r['mjd'])
    return ('{0:4d}{1:4d}{2:4d}{3:7d}{x:11.6f}{y:11.6f}{dut:12.7f}{lod:12.7f}'
            '{dx:11.6f}{dy:11.6f}{x_err:11.6f}{y_err:11.6f}{dut_err:12.7f}'
            '{lod_err:11.7f}{dx_err:12.6f}{dy_err:12.6f}').format(
                d.year, d.month, d.day, r['mjd'], **r)


def main():
    cli = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    cli.add_argument('-c', '--c04', help='local copy of {0}'.format(C04_URL))
    cli.add_argument('-f', '--finals', help='local copy of {0}'.format(FINALS_URL))
    cli.add_argument('-o', '--output', default=OUTPUT)
    args = cli.parse_args()

    c04 = parse_c04_20(read_lines(args.c04, C04_URL))
    finals = parse_finals(read_lines(args.finals, FINALS_URL))

    last_c04 = c04[-1]['mjd']
    tail = [r for r in finals if r['mjd'] > last_c04]
    if not tail or tail[0]['mjd'] != last_c04 + 1:
        raise SystemExit('finals2000A does not continue from 20 C04 MJD {0}'.format(last_c04))
    first_pred = next((r['mjd'] for r in tail if r['predicted']), None)

    def date(mjd):
        return (MJD_EPOCH + datetime.timedelta(days=mjd)).isoformat()

    header = [
        '               EARTH ORIENTATION PARAMETERS FOR JEOD (generated by make_eop_input.py)',
        '',
        '  Generated  : {0}'.format(datetime.date.today().isoformat()),
        '  {0} .. {1}: IERS 20 C04 final values ({2})'.format(
            date(c04[0]['mjd']), date(last_c04), C04_URL),
        '  {0} .. {1}: IERS Bulletin A finals2000A ({2})'.format(
            date(tail[0]['mjd']), date(tail[-1]['mjd']), FINALS_URL),
        '  Predicted values start {0}; regenerate periodically.'.format(
            date(first_pred) if first_pred else 'n/a'),
        '  Columns not provided by Bulletin A (LOD, dX, dY, errors) are written as 0.',
        '',
        '  Layout follows EOP 14 C04:',
        '             FORMAT(3(I4),I7,2(F11.6),2(F12.7),2(F11.6),2(F11.6),2(F11.7),2(F12.6))',
        '##################################################################################',
        '',
        '      Date      MJD      x          y        UT1-UTC       LOD         dX        dY'
        '        x Err     y Err   UT1-UTC Err  LOD Err     dX Err       dY Err  ',
        '                         "          "           s           s          "         "'
        '           "          "          s         s            "           "',
        '     (0h UTC)',
        '',
    ]
    with open(args.output, 'w') as f:
        f.write('\n'.join(header) + '\n')
        for r in c04 + tail:
            f.write(format_row(r) + '\n')

    print('Wrote {0}: {1} .. {2} ({3} C04 + {4} Bulletin A rows, predictions from {5})'.format(
        args.output, date(c04[0]['mjd']), date(tail[-1]['mjd']), len(c04), len(tail),
        date(first_pred) if first_pred else 'n/a'))


if __name__ == '__main__':
    main()
